#!/usr/bin/env node
/**
 * Generates sdks/fivem/lib/endpoints.lua from sdks/spec/endpoints.json.
 *
 *   node sdks/fivem/scripts/gen-endpoints.mjs          # write
 *   node sdks/fivem/scripts/gen-endpoints.mjs --check  # CI: fail if stale
 *
 * The Lua method name of every endpoint is derived here (one rule, written
 * into the output) so the runtime never has to guess:
 *   - kebab-case segments become camelCase      history.ban-templates → history.banTemplates
 *   - server.resource.*  → server.resources.*   (nested group, as in the other SDKs)
 *   - whitelist.approvals (the GET list) → whitelist.approvals.list
 *     (the name "approvals" is also the nested group for add/remove)
 *   - server.kickall → server.kickAll
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const specPath = resolve(here, "..", "..", "spec", "endpoints.json");
const outPath = resolve(here, "..", "lib", "endpoints.lua");

const spec = JSON.parse(readFileSync(specPath, "utf8"));

const SPECIAL = {
  "whitelist.approvals": "whitelist.approvals.list",
  "server.kickall": "server.kickAll",
};

const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

function luaName(id) {
  if (SPECIAL[id]) return SPECIAL[id];
  const parts = id.split(".");
  if (parts[0] === "server" && parts[1] === "resource") parts[1] = "resources";
  return parts.map(camel).join(".");
}

const q = (s) => JSON.stringify(String(s)); // a JSON string is a valid Lua string literal for our ASCII names
const luaStr = (s) => {
  // Lua string literal that is safe for any UTF-8 text (used for summaries).
  return '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n") + '"';
};

const names = new Set();
const lines = [];
lines.push("-- GENERATED by sdks/fivem/scripts/gen-endpoints.mjs from sdks/spec/endpoints.json.");
lines.push("-- Do not edit by hand: run `node sdks/fivem/scripts/gen-endpoints.mjs`.");
lines.push("-- Load this file BEFORE lib/txapi.lua.");
lines.push("");
lines.push("TxApi = TxApi or {}");
lines.push("TxApi._spec = {");
lines.push(`    apiVersion = ${q(spec.apiVersion)},`);
lines.push("    endpoints = {");
for (const e of spec.endpoints) {
  const lua = luaName(e.id);
  if (names.has(lua)) throw new Error(`duplicate Lua method name ${lua}`);
  names.add(lua);
  const pathParams = e.params.filter((p) => p.in === "path").map((p) => p.name);
  // order path params as they appear in the template
  pathParams.sort((a, b) => e.path.indexOf(`{${a}}`) - e.path.indexOf(`{${b}}`));
  const query = e.params.filter((p) => p.in === "query");
  const unknownIn = e.params.filter((p) => p.in !== "query" && p.in !== "path");
  if (unknownIn.length) throw new Error(`${e.id}: unsupported param location ${unknownIn[0].in}`);
  lines.push("        {");
  lines.push(`            id = ${q(e.id)}, lua = ${q(lua)}, method = ${q(e.method)}, path = ${q(e.path)},`);
  lines.push(`            permission = ${e.permission == null ? "nil" : q(e.permission)}, accountLevel = ${e.accountLevel ? "true" : "false"},`);
  lines.push(`            summary = ${luaStr(e.summary ?? "")},`);
  lines.push(`            pathParams = { ${pathParams.map(q).join(", ")} },`);
  lines.push(`            query = { ${query.map((p) => `{ name = ${q(p.name)}, type = ${q(p.type)}, required = ${p.required ? "true" : "false"} }`).join(", ")} },`);
  lines.push(`            hasBody = ${e.body.length > 0 ? "true" : "false"},`);
  lines.push(`            body = { ${e.body.map((b) => `{ name = ${q(b.name)}, type = ${q(b.type)}, required = ${b.required ? "true" : "false"}${b.maxLength ? `, maxLength = ${b.maxLength}` : ""} }`).join(", ")} },`);
  lines.push("        },");
}
lines.push("    },");
lines.push(`    webhookEvents = { ${(spec.webhookEvents ?? []).map(q).join(", ")} },`);
lines.push("}");
lines.push("");
const out = lines.join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
  if (current !== out) {
    console.error("lib/endpoints.lua is stale — run: node sdks/fivem/scripts/gen-endpoints.mjs");
    process.exit(1);
  }
  console.log(`lib/endpoints.lua up to date (${spec.endpoints.length} endpoints, API ${spec.apiVersion})`);
} else {
  writeFileSync(outPath, out);
  console.log(`wrote ${outPath} (${spec.endpoints.length} endpoints, API ${spec.apiVersion})`);
}
